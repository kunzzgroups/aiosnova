const assert=require('node:assert/strict')
const {load,clean}=require('./check-settings-companies.cjs')
const settings=load('src/modules/ai/settings/services/settingsService.ts')
const mcp=load('src/modules/ai/settings/services/mcpService.ts')
const {settingsHealthItems,connectionStatusLabel,providerOverviewActivity}=load('src/modules/ai/settings/services/connectionPresentation.ts')
async function main(){
  const company='company-j1',other='company-j2'
  const providersBefore=clean((await settings.fetchProviders(other)).items)
  const serversBefore=clean(await mcp.fetchMcpServers(other))
  const payload={companyId:company,name:'Pending Provider',baseUrl:'https://pending.example.test/v1',apiKey:'mock-key',enabled:true}
  let provider=await settings.createProvider(payload)
  assert.equal(provider.status,'not_verified')
  assert.equal(provider.lastTestedAt,null)
  assert(providerOverviewActivity(provider)[0].detail.includes('Not verified'))
  const result=await settings.testProviderConnection({providerId:provider.id,baseUrl:provider.baseUrl})
  assert.equal(result.simulated,true)
  assert(result.message.includes('not verified'))
  provider=await settings.fetchProvider(provider.id)
  assert.equal(provider.status,'not_verified')
  assert.equal(provider.lastCheck.checkedAt,result.checkedAt)
  assert(providerOverviewActivity(provider)[0].detail.includes('Simulated'))
  provider.lastCheck.message='mutated clone'
  assert.notEqual((await settings.fetchProvider(provider.id)).lastCheck.message,'mutated clone')
  provider=await settings.updateProvider(provider.id,{...payload,baseUrl:'https://changed.example.test/v1'})
  assert.equal(provider.status,'not_verified')
  assert.equal(provider.lastCheck,undefined)
  assert(providerOverviewActivity(provider)[0].detail.includes('updated'))
  await settings.setProviderEnabled(provider.id,false)
  provider=await settings.setProviderEnabled(provider.id,true)
  assert.equal(provider.status,'not_verified')
  assert(providerOverviewActivity(provider)[0].detail.includes('enabled'))
  const sampleConnected=(await settings.fetchProviders(company)).items.find(item=>item.status==='connected')
  const renamedConnected=await settings.updateProvider(sampleConnected.id,{companyId:company,name:sampleConnected.name+' renamed',baseUrl:sampleConnected.baseUrl,enabled:true})
  assert.equal(renamedConnected.status,'connected')
  assert.equal(providerOverviewActivity(renamedConnected)[0].title,renamedConnected.name)
  assert(providerOverviewActivity(renamedConnected)[0].detail.includes('unchanged'))
  const sampleError=(await settings.fetchProviders(company)).items.find(item=>item.status==='error')
  await settings.testProviderConnection({providerId:sampleError.id,baseUrl:sampleError.baseUrl})
  assert.equal((await settings.fetchProvider(sampleError.id)).status,'error')
  const renamedError=await settings.updateProvider(sampleError.id,{companyId:company,name:sampleError.name+' renamed',baseUrl:sampleError.baseUrl,enabled:true})
  assert.equal(renamedError.status,'error')
  const changedError=await settings.updateProvider(sampleError.id,{companyId:company,name:sampleError.name,baseUrl:'https://new-error-config.example.test',enabled:true})
  assert.equal(changedError.status,'not_verified')
  const staleTest=settings.testProviderConnection({providerId:changedError.id,baseUrl:sampleError.baseUrl})
  await staleTest
  assert.equal((await settings.fetchProvider(changedError.id)).lastCheck,undefined)
  const draft=await settings.testProviderConnection({baseUrl:'invalid'})
  assert.equal(draft.ok,false)
  assert.equal(draft.simulated,true)

  const serverPayload={name:'Pending MCP',url:'https://pending.example.test/mcp',auth:'None',description:'Demo',clientId:'',secret:'',enabled:true}
  let server=await mcp.saveMcpServer(company,serverPayload)
  assert.equal(server.status,'not_verified')
  assert.equal(server.checkedAt,null)
  assert(server.activity[0].message.includes('Not verified'))
  server=await mcp.testMcpServer(company,server.id)
  assert.equal(server.status,'not_verified')
  assert.equal(server.latency,null)
  assert(server.activity[0].message.includes('Simulated'))
  assert(!server.activity[0].message.includes('successful'))
  server=await mcp.saveMcpServer(company,{...serverPayload,url:'https://changed.example.test/mcp'},server.id)
  assert.equal(server.status,'not_verified')
  assert.equal(server.lastCheck,undefined)
  await mcp.toggleMcpServer(company,server.id)
  server=await mcp.toggleMcpServer(company,server.id)
  assert.equal(server.status,'not_verified')
  assert.equal(server.checkedAt,null)
  assert.equal(server.lastCheck,undefined)
  const sampleServer=(await mcp.fetchMcpServers(company)).find(item=>item.status==='error')
  assert.equal((await mcp.testMcpServer(company,sampleServer.id)).status,'error')
  const sampleConnectedServer=(await mcp.fetchMcpServers(company)).find(item=>item.status==='connected')
  const serverRenamed=await mcp.saveMcpServer(company,{...sampleConnectedServer,name:'Renamed sample connection',enabled:true},sampleConnectedServer.id)
  assert.equal(serverRenamed.status,'connected')
  const reconfigured=await mcp.saveMcpServer(company,{...serverRenamed,auth:'API Key',secret:'changed-demo-secret',enabled:true},serverRenamed.id)
  assert.equal(reconfigured.status,'not_verified')
  assert.equal(reconfigured.connectedAt,null)
  assert.equal(reconfigured.lastCheck,undefined)
  await assert.rejects(()=>mcp.saveMcpServer(other,serverPayload,server.id),/not found in this company/)
  const health=settingsHealthItems(company,[provider],[],[server,sampleServer])
  assert.equal(health.length,3)
  assert.equal(health[0].label,'Sample error')
  assert(health.filter(item=>item.status==='not_verified').every(item=>item.label==='Not verified'))
  assert(health.find(item=>item.id===server.id).path.includes(encodeURIComponent(server.id)))
  assert.equal(connectionStatusLabel('not_verified'),'Not verified')
  assert.equal(settingsHealthItems(company,[{...provider,status:'disabled'}],[],[{...server,status:'connected'}]).length,0)
  // Explicit mock outcomes are opt-in and remain clearly separate from validation.
  for(const outcome of ['success','failure','success']){
    const expected=outcome==='success'?'connected':'error'
    const result=await settings.testProviderConnection({companyId:company,providerId:provider.id,baseUrl:provider.baseUrl,outcome})
    assert.equal(result.outcome,outcome)
    assert.equal(result.ok,outcome==='success')
    assert(result.message.startsWith('Mock connection'))
    provider=await settings.fetchProvider(provider.id)
    assert.equal(provider.status,expected)
    const events=providerOverviewActivity(provider)
    assert.equal(events[0].status,outcome==='success'?'success':'error')
    assert.equal(events[0].time,provider.lastCheck.checkedAt)
    assert.equal(provider.lastTestedAt,provider.lastCheck.checkedAt)
    assert.equal(settingsHealthItems(company,[provider],[],[]).length,outcome==='failure'?1:0)
    server=await mcp.testMcpServer(company,server.id,outcome)
    assert.equal(server.status,expected)
    assert.equal(server.lastCheck.outcome,outcome)
    assert.equal(server.lastCheck.time,server.checkedAt)
    assert.equal(server.activity[0].time,server.checkedAt)
    if(outcome==='success')assert.equal(server.connectedAt,server.checkedAt)
    assert(server.activity[0].message.startsWith('Mock connection'))
    assert.equal(server.activity[0].status,outcome==='success'?'success':'error')
    assert.equal(settingsHealthItems(company,[],[],[server]).length,outcome==='failure'?1:0)
  }
  await assert.rejects(()=>settings.testProviderConnection({companyId:other,providerId:provider.id,baseUrl:provider.baseUrl,outcome:'success'}),/not available/)
  await assert.rejects(()=>mcp.testMcpServer(other,server.id,'success'),/not found/)
  await settings.setProviderEnabled(provider.id,false)
  await assert.rejects(()=>settings.testProviderConnection({providerId:provider.id,baseUrl:provider.baseUrl,outcome:'success'}),/Enable/)
  await mcp.toggleMcpServer(company,server.id)
  await assert.rejects(()=>mcp.testMcpServer(company,server.id,'success'),/Enable/)
  provider=await settings.setProviderEnabled(provider.id,true)
  server=await mcp.toggleMcpServer(company,server.id)
  assert.equal(provider.status,'not_verified')
  assert.equal(server.status,'not_verified')
  assert.equal(provider.lastCheck,undefined)
  assert.equal(server.lastCheck,undefined)
  assert.deepEqual(clean((await settings.fetchProviders(other)).items),providersBefore)
  assert.deepEqual(clean(await mcp.fetchMcpServers(other)),serversBefore)
  console.log('Passed: pending vs error, create/edit/enable transitions, simulated checks do not fabricate Connected, diagnostic invalidation, Health labels/routes/order and company isolation.')
}
main().catch(error=>{console.error(error);process.exitCode=1})

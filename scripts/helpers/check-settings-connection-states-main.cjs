const assert = require('node:assert/strict')
module.exports = async ({ load, clean, api }) => {
  const settings = load('src/modules/ai/settings/services/settingsService.ts')
  const { testStoredProviderConnection } = load('src/modules/ai/settings/services/providerApiService.ts')
  const { testModelConnection } = load('src/modules/ai/settings/services/connectionService.ts')
  const mcp = load('src/modules/ai/settings/services/mcpService.ts')
  const { settingsHealthItems, connectionStatusLabel } = load('src/modules/ai/settings/services/connectionPresentation.ts')
  const company = 'company-j1', other = 'company-j2'
  const beforeProviders = clean((await settings.fetchProviders(other)).items)
  const beforeServers = clean(await mcp.fetchMcpServers(other))
  const payload = { companyId: company, name: 'Pending Provider', baseUrl: api.officialUrl, apiKey: 'fake-fixture-key', enabled: true }
  let provider = await settings.createProvider(payload)
  assert.equal(provider.status, 'not_verified')
  assert.equal(provider.lastTestedAt, null)
  assert.equal(provider.lastConnectionTest, undefined)
  for (const [modelId, status] of [['test/invalid', 'error'], ['test/shared-model', 'connected']]) {
    const result = await testStoredProviderConnection(company, provider.id, modelId, provider.version)
    assert.equal(result.ok, status === 'connected')
    assert.equal((await settings.fetchProvider(provider.id)).version, provider.version, 'response alone must not update SQL-derived cache')
    const request = api.calls.at(-1)
    assert.deepEqual(clean(request.body), { companyId: company, modelId, version: provider.version })
    assert(!Object.hasOwn(request.body, 'apiKey'), 'stored verification must not transmit a browser key')
    await settings.fetchProviders(company)
    provider = await settings.fetchProvider(provider.id)
    assert.equal(provider.status, status)
    assert.equal(provider.lastConnectionTest.ok, status === 'connected')
    assert.equal(provider.lastConnectionTest.modelId, modelId)
    assert.equal(provider.version, result.providerVersion)
    assert.equal(provider.lastConnectionTest.checkedAt, provider.lastTestedAt)
    assert.equal(settingsHealthItems(company, [provider], [], []).length, status === 'error' ? 1 : 0)
  }
  const verifiedAt = provider.lastTestedAt
  provider = await settings.updateProvider(provider.id, { ...payload, apiKey: '', name: 'Renamed' }, provider.version)
  assert.equal(provider.status, 'connected')
  assert.equal(provider.lastTestedAt, verifiedAt)
  provider = await settings.setProviderEnabled(provider.id, false, company)
  assert.equal(provider.status, 'disabled')
  await assert.rejects(() => testStoredProviderConnection(company, provider.id, 'test/shared-model', provider.version), /Enable/)
  provider = await settings.setProviderEnabled(provider.id, true, company)
  assert.equal(provider.status, 'connected', 'enable changes preserve stored verification')
  provider = await settings.updateProvider(provider.id, { ...payload, apiKey: 'fake-replacement-key' }, provider.version)
  assert.equal(provider.status, 'not_verified')
  assert.equal(provider.lastConnectionTest, undefined)
  assert.equal(provider.lastTestedAt, null)
  assert.equal(api.providers.get(provider.id).connectionRevision, 1)
  assert.equal(api.providers.get(provider.id).verificationRevision, null)
  assert.equal(api.providers.get(provider.id).verificationLastSuccessAt, verifiedAt)
  await settings.fetchProviders(company)
  assert.equal((await settings.fetchProvider(provider.id)).status, 'not_verified')
  await assert.rejects(() => testStoredProviderConnection(other, provider.id, 'test/shared-model', provider.version), /not found in this company/)
  const row = api.providers.get(provider.id)
  for (const patch of [
    { verificationStatus: 'verified', verificationRevision: 0, verificationModelId: 'test/shared-model', verificationCheckedAt: '2026-10-26T08:00:00Z' },
    { verificationRevision: 1, verificationCheckedAt: null },
  ]) {
    Object.assign(row, patch)
    await settings.fetchProviders(company)
    assert.equal((await settings.fetchProvider(provider.id)).status, 'not_verified')
  }
  const beforeDraft = clean(row)
  assert.equal((await testModelConnection({ baseUrl: 'invalid', apiKey: 'fake-draft-key', modelId: 'test/shared-model' })).ok, false)
  assert.deepEqual(clean(row), beforeDraft, 'draft tests never persist saved verification')
  const reverified = await testStoredProviderConnection(company, provider.id, 'test/shared-model', provider.version)
  assert.equal(reverified.ok, true)
  await settings.fetchProviders(company)
  provider = await settings.fetchProvider(provider.id)
  assert.equal(provider.status, 'connected')
  assert.equal(row.connectionRevision, 1)
  assert.equal(row.verificationRevision, 1)

  // MCP remains local sample data, with explicit simulated outcomes.
  const serverPayload = { name: 'Pending MCP', url: 'https://pending.example.test/mcp', auth: 'None', description: 'Demo', clientId: '', secret: '', enabled: true }
  let server = await mcp.saveMcpServer(company, serverPayload)
  assert.equal(server.status, 'not_verified')
  assert.equal(server.checkedAt, null)
  server = await mcp.testMcpServer(company, server.id)
  assert.equal(server.status, 'not_verified')
  assert.equal(server.latency, null)
  assert(server.activity[0].message.includes('Simulated'))
  assert(!server.activity[0].message.includes('successful'))
  server = await mcp.saveMcpServer(company, { ...serverPayload, url: 'https://changed.example.test/mcp' }, server.id)
  assert.equal(server.lastCheck, undefined)
  const sampleError = (await mcp.fetchMcpServers(company)).find(item => item.status === 'error')
  assert.equal((await mcp.testMcpServer(company, sampleError.id)).status, 'error')
  const connectedServer = (await mcp.fetchMcpServers(company)).find(item => item.status === 'connected')
  const renamed = await mcp.saveMcpServer(company, { ...connectedServer, name: 'Renamed sample', enabled: true }, connectedServer.id)
  assert.equal(renamed.status, 'connected')
  const reconfigured = await mcp.saveMcpServer(company, { ...renamed, auth: 'API Key', secret: 'fake-mcp-secret', enabled: true }, renamed.id)
  assert.equal(reconfigured.status, 'not_verified')
  assert.equal(reconfigured.connectedAt, null)
  assert.equal(reconfigured.lastCheck, undefined)
  const health = settingsHealthItems(company, [{ ...provider, status: 'not_verified' }], [], [server, sampleError])
  assert.equal(health.length, 3)
  assert.equal(health[0].status, 'error')
  assert(health.filter(item => item.status === 'not_verified').every(item => item.label === 'Not verified'))
  assert(health.find(item => item.id === server.id).path.includes(encodeURIComponent(server.id)))
  assert.equal(connectionStatusLabel('not_verified'), 'Not verified')
  assert.equal(settingsHealthItems(company, [{ ...provider, status: 'disabled' }], [], [{ ...server, status: 'connected' }]).length, 0)
  for (const outcome of ['success', 'failure', 'success']) {
    server = await mcp.testMcpServer(company, server.id, outcome)
    assert.equal(server.status, outcome === 'success' ? 'connected' : 'error')
    assert.equal(server.lastCheck.outcome, outcome)
    assert.equal(server.lastCheck.time, server.checkedAt)
    assert.equal(server.activity[0].time, server.checkedAt)
    if (outcome === 'success') assert.equal(server.connectedAt, server.checkedAt)
    assert(server.activity[0].message.startsWith('Mock connection'))
    assert.equal(server.activity[0].status, outcome === 'success' ? 'success' : 'error')
    assert.equal(settingsHealthItems(company, [], [], [server]).length, outcome === 'failure' ? 1 : 0)
  }
  await assert.rejects(() => mcp.saveMcpServer(other, serverPayload, server.id), /not found in this company/)
  await assert.rejects(() => mcp.testMcpServer(other, server.id, 'success'), /not found/)
  await mcp.toggleMcpServer(company, server.id)
  await assert.rejects(() => mcp.testMcpServer(company, server.id, 'success'), /Enable/)
  server = await mcp.toggleMcpServer(company, server.id)
  assert.equal(server.status, 'not_verified')
  assert.equal(server.checkedAt, null)
  assert.equal(server.lastCheck, undefined)
  assert.deepEqual(clean((await settings.fetchProviders(other)).items), beforeProviders)
  assert.deepEqual(clean(await mcp.fetchMcpServers(other)), beforeServers)
  console.log('PASS: SQL Provider DTO/verification API, failures and reload, rename/key invalidation, enabled precedence, stale revisions, draft isolation; local MCP and Health/company boundaries. Simulated HTTP only.')
}

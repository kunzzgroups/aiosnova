const assert=require('node:assert/strict')
const React=require('react')
const {renderToStaticMarkup}=require('react-dom/server')
const {load,clean,mock}=require('./check-settings-companies.cjs')
mock('src/modules/ai/settings/components/SettingsDrawer.tsx',{
  SettingsDrawer:({open,children,footer})=>open?React.createElement('section',null,children,footer):null,
})
const mcp=load('src/modules/ai/settings/services/mcpService.ts')
const {McpConnectionCheck}=load('src/modules/ai/settings/components/McpConnectionCheck.tsx')
const {McpAccessDrawer}=load('src/modules/ai/settings/components/McpDrawers.tsx')
async function main(){
  const company='company-j1',servers=await mcp.fetchMcpServers(company)
  const server=servers.find(server=>server.status==='connected')
  const other=clean(await mcp.fetchMcpServers('company-j2'))
  const initial=renderToStaticMarkup(React.createElement(McpConnectionCheck,{server,busy:false,checking:false,onCheck(){}}))
  assert(initial.includes('No simulated check run yet'))
  const checked=await mcp.testMcpServer(company,server.id)
  assert.equal(checked.status,server.status)
  assert.equal(checked.latency,server.latency)
  assert.equal(checked.errors,server.errors)
  assert.equal(checked.lastCheck.time,checked.checkedAt)
  assert(checked.lastCheck.message.includes('not verified'))
  const checkedMarkup=renderToStaticMarkup(React.createElement(McpConnectionCheck,{server:checked,busy:false,checking:false,onCheck(){}}))
  assert(checkedMarkup.includes('Simulated'))
  assert(checkedMarkup.includes('Last checked'))
  assert(checkedMarkup.includes('connection status unchanged'))
  assert(checkedMarkup.includes('No live connection was tested'))
  const saving=renderToStaticMarkup(React.createElement(McpConnectionCheck,{server:checked,busy:true,checking:true,onCheck(){}}))
  assert(saving.includes('Testing…')&&saving.includes('disabled'))
  const drawer=renderToStaticMarkup(React.createElement(McpAccessDrawer,{server:checked,onClose(){},onSaved(){}}))
  assert(drawer.includes('Connection details'))
  assert(drawer.includes('Permissions'))
  assert(!drawer.includes('<dt>Models</dt>'))
  const unchanged=await mcp.saveMcpServer(company,{...checked,enabled:true},checked.id)
  assert.deepEqual(clean(unchanged.lastCheck),clean(checked.lastCheck))
  const changed=await mcp.saveMcpServer(company,{...checked,url:'https://updated.example.test/mcp',enabled:true},checked.id)
  assert.equal(changed.lastCheck,undefined)
  assert.equal(changed.checkedAt,null)
  const disabled=servers.find(server=>server.status==='disabled')
  await assert.rejects(()=>mcp.testMcpServer(company,disabled.id),/Enable/)
  assert.deepEqual(clean(await mcp.fetchMcpServers('company-j2')),other)
  console.log('Passed: simulated check result/time, no fabricated health changes, busy UI, read-only permissions, no static Models, config invalidation and company isolation.')
}
main().catch(error=>{console.error(error);process.exitCode=1})
